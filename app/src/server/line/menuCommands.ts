// リッチメニューのタップを処理する。
//
// 重要な制約: リッチメニューのタイルに「URLを開く」を設定すると全員が同じURLに飛ぶ。
// うちの決済リンクは事業所ごとの署名トークン付き（誰の支払いか特定するため）なので貼れない。
// そこでタイルは「メッセージを送る」アクションにし、Webhookで送信者を特定してから
// その人専用のリンクを返す。ここはその受け口。
//
// ヒアリング/編集より先に判定する必要がある（でないと「料金プラン」が編集指示として
// AIに渡ってしまう）。

export const MENU = {
  PRICING: "料金プラン",
  HOWTO: "使い方",
  PRO: "プロに相談",
  FAQ: "よくある質問",
} as const;

export type MenuCommand = (typeof MENU)[keyof typeof MENU];

/** リッチメニュー由来の操作か判定する。該当しなければ null。 */
export function parseMenuCommand(text: string): MenuCommand | null {
  const t = text.trim();
  for (const value of Object.values(MENU)) {
    if (t === value) return value;
  }
  return null;
}

